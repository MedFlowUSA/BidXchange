import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { localTestDatabase } from './local-test-db.mjs';
test('source registry and normalized opportunities preserve tenant and submission boundaries', async()=>{
 const db=await localTestDatabase({includeCompanySeed:false});
 const admin='80000000-0000-4000-8000-000000000001', viewer='80000000-0000-4000-8000-000000000002', foreign='80000000-0000-4000-8000-000000000003';
 const as=async(user,role='authenticated')=>{ await db.query('reset role');await db.query("select set_config('request.jwt.claim.sub',$1,false)",[user]);await db.query(`set role ${role}`); };
 try {
  for(const file of ['20260919000500_ai_readonly.sql','20260921001600_structured_company_profiles.sql','20260921001700_source_registry.sql','20260921001800_company_source_capabilities.sql']) await db.query(readFileSync('supabase/migrations/'+file,'utf8'));
  await db.query('insert into auth.users(id) values($1),($2),($3)',[admin,viewer,foreign]);
  const org=(await db.query("insert into public.organizations(legal_name,operating_name,slug) values('Synthetic','Synthetic','source-test') returning id")).rows[0].id;
  const other=(await db.query("insert into public.organizations(legal_name,operating_name,slug) values('Foreign','Foreign','source-other') returning id")).rows[0].id;
  await db.query("insert into public.organization_memberships(organization_id,user_id,role) values($1,$2,'organization_admin'),($1,$3,'viewer'),($4,$5,'organization_admin')",[org,admin,viewer,other,foreign]);
  await as(admin);
  await db.query("insert into public.source_registrations(organization_id,source_id,registration_status,evidence_reference) values($1,'cal-eprocure','registered','Reviewed vendor record')",[org]);
  await assert.rejects(db.query("insert into public.source_registrations(organization_id,source_id) values($1,'rampla')",[other]));
  await as(viewer);
  assert.equal((await db.query('select count(*)::int n from public.source_registrations')).rows[0].n,1);
  await assert.rejects(db.query("insert into public.source_registrations(organization_id,source_id) values($1,'rampla')",[org]));
  assert.equal((await db.query("update public.source_registrations set vendor_number='forged' returning id")).rows.length,0);
  await as(foreign);
  assert.equal((await db.query('select count(*)::int n from public.source_registrations')).rows[0].n,0);
  await as(admin);
  const details={schema:1,sourceId:'gsa-ebuy',connectionMode:'manual',lastSynchronizedAt:null,dataConfidence:null};
  const insert=(d)=>db.query("insert into public.opportunities(organization_id,title,source_details) values($1,'Synthetic bid',$2::jsonb) returning id,updated_at",[org,JSON.stringify(d)]);
  await assert.rejects(insert(details));
  await assert.rejects(db.query("insert into public.opportunities(organization_id,title,source_url) values($1,'Synthetic bypass','https://www.ebuy.gsa.gov/')",[org]));
  await db.query("insert into public.source_registrations(organization_id,source_id,registration_status,schedule_number,evidence_reference,expires_on) values($1,'gsa-ebuy','registered','SYNTHETIC-SCHEDULE','Synthetic evidence',current_date+10)",[org]);
  const saved=(await insert(details)).rows[0];
  assert.ok(saved.id);
  await assert.rejects(insert({...details,connectionMode:'official_api'}));
  await assert.rejects(insert({...details,lastSynchronizedAt:new Date().toISOString()}));
  await assert.rejects(insert({...details,dataConfidence:100}));
  await assert.rejects(db.query('update public.source_registrations set organization_id=$1 where organization_id=$2',[other,org]));
  assert.equal((await db.query('select * from public.source_registry_counts($1)',[org])).rows[0].active_count,1);
  await as(foreign);
  assert.equal((await db.query('select * from public.source_registry_counts($1)',[org])).rows.length,0);
  await as(admin);
  await db.query("update public.source_registrations set expires_on=current_date-1 where source_id='gsa-ebuy'");
  await assert.rejects(insert(details));
  assert.equal((await db.query("select count(*)::int n from public.audit_events where entity_table='source_registrations'")).rows[0].n,3);
  await as('', 'anon');
  await assert.rejects(db.query('select * from public.source_registrations'));
  await assert.rejects(db.query('select * from public.source_registry_counts($1)',[org]));
  await db.query('reset role');
  assert.equal((await db.query("select count(*)::int n from pg_trigger where tgrelid='public.profile_facts'::regclass and tgname='aa_structured_fact'")).rows[0].n,1);
 } finally { await db.end(); }
});
